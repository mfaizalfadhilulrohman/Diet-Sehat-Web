# Hidangan jadi dicek lebih dulu daripada bahan, supaya "Soto ayam bening" dijelaskan sebagai soto, bukan sebagai ayam.
HIDANGAN = ("gado", "pecel", "karedok", "ketoprak", "soto", "bakso", "sate", "rawon", "nasi padang", "pepes", "orak-arik", "capcay",
            "urap", "omelet", "bola daging", "bubur", "nasi tim", "mi ayam")
URUTAN = ([c for c in CATATAN if c[0] in HIDANGAN] + [c for c in CATATAN if c[0] not in HIDANGAN])


def untuk(f):
    """(alasan, saran) untuk satu frame makanan. Frame wajib punya: nama, k, g, kkal, protein, karbo, lemak, serat, ig."""
    n = f["nama"].lower() + " "
    for kata, alasan, saran in URUTAN:
        if kata in n:
            return alasan, saran
    return _umum(f), _saran_umum(f)
