def _umum(f):
    """Alasan umum dari nilai gizi jika tidak ada catatan khusus."""
    a = []
    if f["protein"] >= 15: a.append(f"tinggi protein ({f['protein']:g} g) sehingga menjaga massa otot dan mengenyangkan")
    elif f["protein"] >= 6: a.append(f"mengandung protein ({f['protein']:g} g)")
    if f["serat"] >= 3.5: a.append(f"kaya serat ({f['serat']:g} g) sehingga kenyang lebih lama")
    elif f["serat"] >= 1.5: a.append(f"memberi serat ({f['serat']:g} g)")
    if f["kkal"] <= 60 and f["g"] >= 80: a.append("kalorinya rendah dibanding volumenya")
    if f["lemak"] <= 3 and f["kkal"] >= 60: a.append("rendah lemak")
    if f["ig"] == "rendah" and f["karbo"] >= 10: a.append("indeks glikemik rendah sehingga energi dilepas pelan")
    if not a: a.append("memberi energi dan melengkapi variasi menu harian")
    return "Pilihan ini " + ", ".join(a) + "."


